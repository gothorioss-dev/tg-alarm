            ['22-28', '24а', ''],
            ['21-33', '22', null],
            ['1-4', '2', ''],
            ['134-182 парні', '150', ''],
            ['134-182 парні', '151', null],
            ['249-293 непарні', '251', ''],
            ['6 (5 пов)', '6', '5 пов'],
            ['20(3ф)', '20', '3ф'],
            ['1  (1 та 2 пов)', '1', '1 та 2 пов'],
            ['5 (1, 2 пов)|7', '7', ''],
            ['6 (5 пов)|6', '6', ''],
            ['21 п.1-4|21 п.5-8', '21', 'п.1-4; п.5-8'],
            ['43/Тургенєва24', '43', 'тургенєва24'],
            ['115/5', '115/5', ''],
            ['115/5', '115', null],
            ['11,13', '13', ''],
